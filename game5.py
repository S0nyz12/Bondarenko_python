# --- Заголовок ------------------------------------
title = "СОЛЯНЫЕ ШАХТЫ"
frame = "=" * 19
print(frame)
print(" " + title + " ")
print(frame)
print()

# --- Знакомство с героем --------------------------
print("Как зовут героя?")
hero_name = input()
print(f"Добро пожаловать, {hero_name}!")
print(
    "Ты входишь в соляные шахты. Вокруг темно, стены покрыты "
    "солью, а из глубины доносится странный шум."
)
print()

# --- Настройка героя -------------------------------
print("Настройка героя.")
print("Здоровье, сила, ловкость, выносливость — по одному числу в строке:")
health = int(input())
strength = int(input())
agility = int(input())
endurance = int(input())

# --- Расчёт характеристик --------------------------
base_attack = 10
damage = base_attack + strength * 1.5
crit_damage = damage * 2

# Запас сил зависит от выносливости.
max_stamina = endurance * 2 + 6
stamina = max_stamina

# --- Формуляр героя --------------------------------
print()
print("Характеристики героя:")
print(f"Здоровье: {health}")
print(f"Сила: {strength}")
print(f"Ловкость: {agility}")
print(f"Выносливость: {endurance}")
print(f"Урон героя: {damage:.1f}")
print(f"Критический урон: {crit_damage:.1f}")
print(f"Запас сил: {stamina}/{max_stamina}")
print()

# --- Главный цикл игры -----------------------------
running = True
actions = 0
valid = ("0", "1", "2", "3", "4", "5", "6")

while running:
    print("Что делаешь?")
    print("1 - осмотреться")
    print("2 - идти вперёд")
    print("3 - отдохнуть")
    print("4 - прислушаться")
    print("5 - зажечь факел")
    print("6 - тренировка")
    print("0 - выйти из подземелья")

    # Защита от неверного ввода: ошибка не тратит игровой ход.
    choice = input()
    while choice not in valid:
        print("Такого пункта нет. Введи номер пункта из меню.")
        choice = input()

    # --- Выбор действия -----------------------------
    match choice:
        case "1":
            print("Вы осмотрелись. Комната пуста, только пыль на полу.")

        case "2":
            cost = 2
            if stamina >= cost:
                stamina -= cost
                print("Вы осторожно идёте вперёд. Пол скрипит под ногами.")
            else:
                health -= cost - stamina
                stamina = 0
                print("Сил больше нет — вы идёте на одном упорстве.")

        case "3":
            stamina = min(max_stamina, stamina + 4)
            print("Вы немного отдохнули и восстановили силы.")

        case "4":
            print("Вы прислушались. Вдалеке слышен странный шум.")

        case "5":
            if stamina >= 1:
                stamina -= 1
                print("Вы зажгли факел. Стало немного светлее.")
            else:
                health -= 1
                print("Сил не осталось. Вы зажигаете факел, обжигая руки, и теряете 1 здоровье.")

        case "6":
            stamina = max(0, stamina - 1)
            strength += 1
            damage = base_attack + strength * 1.5
            crit_damage = damage * 2
            print("Вы тренируетесь. Сила увеличилась на 1, но тренировка утомила вас.")

        case "0":
            print("Вы выбираетесь из соляных шахт к свежему воздуху.")
            running = False

    # Считаем только игровые действия, но не выход из игры.
    if running:
        actions += 1
        print()
        print(f"Здоровье: {health} Запас сил: {stamina}/{max_stamina}")

        # Проверяем гибель после любого действия, которое могло отнять здоровье.
        if health <= 0:
            print(f"{hero_name} падает без сил. Соляные шахты поглощают последний звук шагов.")
            running = False

# --- Прощание после цикла ---------------------------
print()
print(frame)
if health <= 0:
    print(f"Ты не дошёл, {hero_name}. Действий совершено: {actions}.")
else:
    print(f"Забег окончен, {hero_name}. Действий совершено: {actions}.")
print(frame)